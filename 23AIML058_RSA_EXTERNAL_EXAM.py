import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

from fairlearn.metrics import (
    MetricFrame,
    selection_rate,
    true_positive_rate,
    false_positive_rate,
    demographic_parity_difference,
    demographic_parity_ratio,
    equalized_odds_difference
)

from fairlearn.postprocessing import ThresholdOptimizer

df = pd.read_csv("/content/adult.csv")

print("Dataset shape:", df.shape)

df.head()

print(df.columns.tolist())

print("Missing '?' values in each column:")
print((df == "?").sum())

df = df.replace("?", np.nan)
df = df.dropna()

print("Shape after removing '?':", df.shape)

print(df.isnull().sum().sum())

df.head()

print("Income:")
print(df["income"].value_counts())

print("\nSex:")
print(df["sex"].value_counts())

df["income"] = df["income"].apply(
    lambda x: 1 if ">50K" in x else 0
)

print(df["income"].value_counts())

A = df["sex"]

X = df.drop(columns=["income", "sex"])

y = df["income"]

print("Features:")
print(X.columns.tolist())

print("\nSensitive attribute:")
print(A.name)

print("\nTarget:")
print(y.name)

X_train, X_test, y_train, y_test, A_train, A_test = train_test_split(
    X,
    y,
    A,
    test_size=0.30,
    random_state=42,
    stratify=y
)

print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

numeric_features = X.select_dtypes(
    include=["int64", "float64"]
).columns

categorical_features = X.select_dtypes(
    include=["object"]
).columns

print("Numerical features:")
print(list(numeric_features))

print("\nCategorical features:")
print(list(categorical_features))

preprocessor = ColumnTransformer(
    transformers=[
        ("num", StandardScaler(), numeric_features),
        ("cat", OneHotEncoder(handle_unknown="ignore"), categorical_features)
    ]
)

model = Pipeline([
    ("preprocessor", preprocessor),
    ("classifier", LogisticRegression(max_iter=1000))
])

model.fit(X_train, y_train)

print("Logistic Regression model trained successfully.")

y_pred = model.predict(X_test)

baseline_accuracy = accuracy_score(y_test, y_pred)

print("Baseline Accuracy:", round(baseline_accuracy, 4))

metrics = {
    "Accuracy": accuracy_score,
    "Selection Rate": selection_rate,
    "TPR": true_positive_rate,
    "FPR": false_positive_rate
}

baseline_mf = MetricFrame(
    metrics=metrics,
    y_true=y_test,
    y_pred=y_pred,
    sensitive_features=A_test
)

print(baseline_mf.by_group)

baseline_dp_diff = demographic_parity_difference(
    y_test,
    y_pred,
    sensitive_features=A_test
)

baseline_dp_ratio = demographic_parity_ratio(
    y_test,
    y_pred,
    sensitive_features=A_test
)

baseline_eo_diff = equalized_odds_difference(
    y_test,
    y_pred,
    sensitive_features=A_test
)

print("Demographic Parity Difference:",
      round(baseline_dp_diff, 4))

print("Demographic Parity Ratio:",
      round(baseline_dp_ratio, 4))

print("Equalized Odds Difference:",
      round(baseline_eo_diff, 4))

print("========== BASELINE MODEL ==========")
print("Accuracy:", round(baseline_accuracy, 4))
print("DP Difference:", round(baseline_dp_diff, 4))
print("DP Ratio:", round(baseline_dp_ratio, 4))
print("EO Difference:", round(baseline_eo_diff, 4))

to_dp = ThresholdOptimizer(
    estimator=model,
    constraints="demographic_parity",
    predict_method="decision_function"
)

to_dp.fit(
    X_train,
    y_train,
    sensitive_features=A_train
)

y_pred_dp = to_dp.predict(
    X_test,
    sensitive_features=A_test
)

print("Demographic Parity ThresholdOptimizer completed.")

acc_dp = accuracy_score(y_test, y_pred_dp)

dp_diff_dp = demographic_parity_difference(
    y_test,
    y_pred_dp,
    sensitive_features=A_test
)

dp_ratio_dp = demographic_parity_ratio(
    y_test,
    y_pred_dp,
    sensitive_features=A_test
)

eo_diff_dp = equalized_odds_difference(
    y_test,
    y_pred_dp,
    sensitive_features=A_test
)

print("===== DEMOGRAPHIC PARITY MITIGATION =====")
print("Accuracy:", round(acc_dp, 4))
print("DP Difference:", round(dp_diff_dp, 4))
print("DP Ratio:", round(dp_ratio_dp, 4))
print("EO Difference:", round(eo_diff_dp, 4))

mf_dp = MetricFrame(
    metrics=metrics,
    y_true=y_test,
    y_pred=y_pred_dp,
    sensitive_features=A_test
)

print(mf_dp.by_group)

to_eo = ThresholdOptimizer(
    estimator=model,
    constraints="equalized_odds",
    predict_method="decision_function"
)

to_eo.fit(
    X_train,
    y_train,
    sensitive_features=A_train
)

y_pred_eo = to_eo.predict(
    X_test,
    sensitive_features=A_test
)

print("Equalized Odds ThresholdOptimizer completed.")

acc_eo = accuracy_score(y_test, y_pred_eo)

dp_diff_eo = demographic_parity_difference(
    y_test,
    y_pred_eo,
    sensitive_features=A_test
)

dp_ratio_eo = demographic_parity_ratio(
    y_test,
    y_pred_eo,
    sensitive_features=A_test
)

eo_diff_eo = equalized_odds_difference(
    y_test,
    y_pred_eo,
    sensitive_features=A_test
)

print("===== EQUALIZED ODDS MITIGATION =====")
print("Accuracy:", round(acc_eo, 4))
print("DP Difference:", round(dp_diff_eo, 4))
print("DP Ratio:", round(dp_ratio_eo, 4))
print("EO Difference:", round(eo_diff_eo, 4))

mf_eo = MetricFrame(
    metrics=metrics,
    y_true=y_test,
    y_pred=y_pred_eo,
    sensitive_features=A_test
)

print(mf_eo.by_group)

baseline_sel_m = baseline_mf.by_group.loc["Male", "Selection Rate"]
baseline_sel_f = baseline_mf.by_group.loc["Female", "Selection Rate"]

dp_sel_m = mf_dp.by_group.loc["Male", "Selection Rate"]
dp_sel_f = mf_dp.by_group.loc["Female", "Selection Rate"]

eo_sel_m = mf_eo.by_group.loc["Male", "Selection Rate"]
eo_sel_f = mf_eo.by_group.loc["Female", "Selection Rate"]

comparison = pd.DataFrame({
    "MODEL": [
        "Baseline",
        "TO: demographic_parity",
        "TO: equalized_odds"
    ],

    "ACC": [
        baseline_accuracy,
        acc_dp,
        acc_eo
    ],

    "SEL_M": [
        baseline_sel_m,
        dp_sel_m,
        eo_sel_m
    ],

    "SEL_F": [
        baseline_sel_f,
        dp_sel_f,
        eo_sel_f
    ],

    "DP_DIFF": [
        baseline_dp_diff,
        dp_diff_dp,
        dp_diff_eo
    ],

    "EO_DIFF": [
        baseline_eo_diff,
        eo_diff_dp,
        eo_diff_eo
    ]
})

comparison = comparison.round(4)

comparison

groups = ["Male", "Female"]

baseline_values = [baseline_sel_m, baseline_sel_f]
dp_values = [dp_sel_m, dp_sel_f]
eo_values = [eo_sel_m, eo_sel_f]

x = np.arange(len(groups))
width = 0.25

plt.figure(figsize=(8, 5))

plt.bar(
    x - width,
    baseline_values,
    width,
    label="Baseline"
)

plt.bar(
    x,
    dp_values,
    width,
    label="Demographic Parity"
)

plt.bar(
    x + width,
    eo_values,
    width,
    label="Equalized Odds"
)

plt.xlabel("Sex")
plt.ylabel("Selection Rate")
plt.title("Selection Rate by Sex")

plt.xticks(x, groups)
plt.legend()

plt.tight_layout()

plt.savefig(
    "selection_rate_by_sex.png",
    dpi=300
)

plt.show()

comparison.to_csv(
    "fairness_comparison.csv",
    index=False
)

print("Saved: fairness_comparison.csv")

print("Accuracy loss with Demographic Parity:",
      round(baseline_accuracy - acc_dp, 4))

print("Accuracy loss with Equalized Odds:",
      round(baseline_accuracy - acc_eo, 4))

